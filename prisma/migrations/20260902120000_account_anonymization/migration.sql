-- Anonimização de conta, em vez de exclusão física.
--
-- Metade das FKs que apontam para `accounts` é ON DELETE RESTRICT e nunca some
-- do banco (preferences, integrations, organization_users, organizations,
-- support_tickets), então `DELETE FROM accounts` levantava violação de chave
-- estrangeira para qualquer usuário real. A exclusão passa a apagar o dado
-- pessoal e manter a linha, e esta coluna é o que marca a conta como encerrada.
--
-- Sem índice próprio: a única consulta que filtra por ela é a busca por e-mail,
-- que já entra pelo índice único de `email` e lê `deleted_at` da mesma linha.
ALTER TABLE "accounts" ADD COLUMN "deleted_at" TIMESTAMP(3);
