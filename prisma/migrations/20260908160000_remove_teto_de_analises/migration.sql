-- Sai o teto que ninguém aplicava
--
-- `max_monthly_analyses` nasceu duas migrações atrás para o contrato governar o
-- número que a barra de "Análises por mês" mostrava. A linha saiu do catálogo e
-- da tela, e a coluna vai junto.
--
-- ## Por que a linha saiu
--
-- Ela era **derivada**, não independente: os achados vêm dos anúncios que a
-- régua da noite deixou entrar, e isso é `monitored-ads`. Eram dois números
-- descrevendo a mesma restrição, e o que ninguém aplicava era o que ninguém
-- revisitava. Pior: com o rodízio da varredura ela passaria a prometer **menos**
-- do que o produto entrega — e um número assim é convite para alguém
-- "consertá-lo" pondo um teto de verdade onde nunca houve um.
--
-- ## Por que dropar em vez de deixar quieta
--
-- Coluna anulável sem leitor é barata em disco e cara em leitura: a próxima
-- pessoa a abrir `organization_quotas` encontraria um teto de análises e
-- concluiria que existe uma guarda para ele. Nenhuma organização chegou a ter
-- valor aqui — a coluna viveu dois dias e nunca teve caminho de escrita em
-- produção.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE "organization_quotas" DROP COLUMN IF EXISTS "max_monthly_analyses";
